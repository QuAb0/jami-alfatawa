// بيانات تجريبية لتجربة الواجهة فقط (نصوص الأجوبة ليست فتاوى حقيقية)
// الاستخدام: npm run demo   — وتُحذف من لوحة الإدارة بزر «حذف البيانات التجريبية»
const { saveFatwa } = require('../server/db');
const sheikhs = require('../server/sheikhs').all();

const topics = [
  ['حكم المسح على الجورب المخرق', 'ما حكم المسح على الجورب إذا كان فيه خرق أو شق صغير؟', 'taharah'],
  ['من نسي ركعة من الصلاة', 'صليت الظهر ثلاث ركعات ناسياً ثم تذكرت بعد السلام، فماذا أفعل؟', 'salah'],
  ['زكاة الذهب المعد للبس', 'هل تجب الزكاة في ذهب المرأة الذي تلبسه للزينة؟', 'zakah'],
  ['الجمع بين الصلاتين للمسافر النازل', 'هل يجوز للمسافر إذا نزل في بلد أن يجمع بين الصلاتين؟', 'salah'],
  ['من أفطر في رمضان ناسياً', 'أكلت في نهار رمضان ناسياً، فهل صيامي صحيح؟', 'siyam'],
  ['بيع التقسيط بزيادة في الثمن', 'ما حكم بيع السلعة بالتقسيط بثمن أعلى من ثمنها نقداً؟', 'muamalat'],
  ['بر الوالدين بعد موتهما', 'كيف أبر والدي بعد وفاتهما؟', 'adab'],
  ['قراءة القرآن للحائض', 'هل يجوز للحائض أن تقرأ القرآن من حفظها؟', 'taharah'],
  ['حكم أكل الربا والفوائد البنكية', 'ما حكم أخذ الفوائد من البنك ووضع المال في حساب ربوي؟', 'muamalat'],
  ['حكم التدخين وبيع الدخان', 'ما حكم شرب الدخان وبيعه؟', 'atimah'],
  ['حكم الاستماع إلى الأغاني والموسيقى', 'ما حكم سماع الأغاني والمعازف؟', 'adab'],
  ['الطلاق في حال الغضب الشديد', 'طلقت زوجتي وأنا غضبان جداً فهل يقع الطلاق؟', 'usrah'],
];

let n = 0;
sheikhs.forEach((s, si) => {
  topics.forEach(([title, question, category], ti) => {
    if ((ti + si) % 4 === 3) return;   // تنويع: ليس لكل شيخ فتوى في كل مسألة
    const answer = `[نص تجريبي] هنا يظهر جواب ${s.name} عن مسألة «${title}» منقولاً من موقعه الرسمي بألفاظه كما هي، بعد تشغيل أداة الجمع.\n\n` +
      `هذا النص لعرض شكل الصفحة فقط وليس فتوى، ولا يجوز نسبته إلى الشيخ. ${question}`;
    saveFatwa({
      sheikh_id: s.id, url: `https://${s.site.domain}/#demo-${ti}`, title, question, answer, category, demo: true,
      summary: `[خلاصة تجريبية] تظهر هنا خلاصة جواب ${s.short} في المسألة.`,
    });
    n++;
  });
});
console.log(`أُضيفت ${n} فتوى تجريبية`);
