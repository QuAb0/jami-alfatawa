let STOP;
function dialectToFusha(s) {
  return normalize(s).split(' ').map(w => DIALECT[w] || (w.startsWith('ال') && DIALECT[w.slice(2)] ? 'ال' + DIALECT[w.slice(2)] : w)).join(' ');
}

// تجذير خفيف: إزالة أل التعريف وحروف العطف والجر الملتصقة واللواحق الشائعة
function stem(w) {
  if (w.length <= 3) return w;
  w = w.replace(/^(وال|بال|فال|كال|لل|ال)/, '');
  if (w.length > 4) w = w.replace(/^[وفب]/, '');
  if (w.length > 4) w = w.replace(/(هما|ات|ون|ين|ان|ها|هم|نا|كم|يه|ه)$/, '');
  return w;
}

function tokens(s) {
  return dialectToFusha(s).split(' ').filter(w => w && !STOP.has(w) && w.length > 1).map(stem).filter(w => w.length > 1);
}

// نص مُفهرس: كلمات مجذرة
const indexText = s => normalize(s).split(' ').map(stem).join(' ');

STOP = new Set(STOP_WORDS.map(normalize));
const SYN_MAP = new Map();
for (const g of SYNONYMS) { const st = [...new Set(g.flatMap(w => normalize(w).split(' ')).map(stem))]; for (const w of st) SYN_MAP.set(w, st); }
// يحوّل كلمات السؤال إلى مجموعات مفاهيم (كل مفهوم = كلمة + مرادفاتها)
function concepts(words) {
  const seen = new Set(), out = [];
  for (const w of words) { if (seen.has(w)) continue; const g = SYN_MAP.get(w) || [w]; g.forEach(x => seen.add(x)); out.push(g); }
  return out;
}
const isStop = w => STOP.has(w);
module.exports = { normalize, dialectToFusha, tokens, stem, indexText, concepts, isStop };
